#!/usr/bin/env python
"""Embed the current package source into kaggle_runner.ipynb as a base64 blob.

This makes every `kaggle kernels push` ship the exact current code, so the
runner no longer depends on the p300former-paper dataset being in sync
(the dataset remains the official publication artifact).

  python scripts/embed_code_into_runner.py
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_NOTEBOOK = PROJECT_ROOT / "kaggle" / "p300vit-leakfree.ipynb"
BLOB_CELL_MARKER = "EMBEDDED-CODE-BLOB"

EXCLUDE_DIRS = {"__pycache__", ".git", ".venv", "venv", "results", "figures", "cache",
                ".ipynb_checkpoints", ".pytest_cache", "kaggle_audit", "kaggle"}
EXCLUDE_PREFIXES = ("kaggle_results", "embedded_code")
EXCLUDE_DIR_PREFIXES = (".venv", "venv", ".eggs")
EXCLUDE_FILES = {"p300former-paper.zip", "kaggle_runner.ipynb"}


def build_blob() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(PROJECT_ROOT.rglob("*")):
            if path.is_dir():
                continue
            rel = path.relative_to(PROJECT_ROOT)
            if any(part in EXCLUDE_DIRS for part in rel.parts):
                continue
            if any(part.startswith(EXCLUDE_DIR_PREFIXES) for part in rel.parts):
                continue
            if rel.parts and rel.parts[0].startswith(EXCLUDE_PREFIXES):
                continue
            if path.name in EXCLUDE_FILES or path.suffix in (".pyc", ".ipynb"):
                continue
            zf.write(path, arcname=str(rel))
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main() -> None:
    global NOTEBOOK
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--notebook", default=str(DEFAULT_NOTEBOOK),
                    help="notebook to embed the code blob into")
    args = ap.parse_args()
    NOTEBOOK = Path(args.notebook)
    nb = json.loads(NOTEBOOK.read_text())
    blob = build_blob()
    print(f"package blob: {len(blob)/1024:.0f} KB base64")

    src_code = (
        "# " + BLOB_CELL_MARKER + " -- auto-generated by scripts/embed_code_into_runner.py\n"
        "# Extracts the current package source shipped inside this notebook, so the\n"
        "# runner always executes exactly this code version (dataset stays authoritative\n"
        "# for the final publication archive).\n"
        "import os, base64, io, zipfile\n"
        "_B64 = (\n"
    )
    chunk = 100_000
    lines = [blob[i:i + chunk] for i in range(0, len(blob), chunk)]
    for l in lines:
        src_code += f'    "{l}"\n'
    src_code += (
        ")\n"
        "_EMBEDDED_ROOT = '/kaggle/working/embedded_code'\n"
        "os.makedirs(_EMBEDDED_ROOT, exist_ok=True)\n"
        "with zipfile.ZipFile(io.BytesIO(base64.b64decode(_B64))) as zf:\n"
        "    zf.extractall(_EMBEDDED_ROOT)\n"
        "print('[info] embedded package extracted ->', _EMBEDDED_ROOT)\n"
    )

    # find discovery cell; insert embed cell right before it
    disc_idx = None
    for i, c in enumerate(nb["cells"]):
        txt = "".join(c["source"]) if isinstance(c["source"], list) else c["source"]
        if c["cell_type"] == "code" and "locate the codebase" in txt:
            disc_idx = i
            break
    assert disc_idx is not None, "discovery cell not found"

    # replace an existing blob cell if present
    blob_idx = None
    for i, c in enumerate(nb["cells"]):
        txt = "".join(c["source"]) if isinstance(c["source"], list) else c["source"]
        if c["cell_type"] == "code" and BLOB_CELL_MARKER in txt:
            blob_idx = i
            break

    new_cell = {"cell_type": "code", "metadata": {}, "outputs": [],
                "execution_count": None, "source": src_code}
    if blob_idx is not None:
        nb["cells"][blob_idx] = new_cell
    else:
        nb["cells"].insert(disc_idx, new_cell)
        disc_idx += 1

    # discovery cell: prefer the embedded package over the dataset
    disc = nb["cells"][disc_idx]
    txt = disc["source"]
    if isinstance(txt, list):
        txt = "".join(txt)
    if "prefer embedded" not in txt:
        txt = txt.replace(
            "CODE_ROOT = find_code_root()\n",
            "CODE_ROOT = _EMBEDDED_ROOT if os.path.isdir(\n"
            "    os.path.join(_EMBEDDED_ROOT, 'src', 'p300former')) else find_code_root()\n"
            "# prefer embedded package; fall back to the dataset copy\n",
        )
        disc["source"] = txt.splitlines(keepends=True)

    NOTEBOOK.write_text(json.dumps(nb, indent=1))
    print(f"notebook updated: {len(nb['cells'])} cells, blob embedded, discovery prefers embedded code")


if __name__ == "__main__":
    main()
